package main

import (
	"net"
	"net/http"

	"context"
	"sync"

	"github.com/gorilla/rpc"
	"github.com/ochinchina/gorilla-xmlrpc/xml"
)

// XMLRPC mange the XML RPC servers
// start XML RPC servers to accept the XML RPC request from client side
type XMLRPC struct {
	mu        sync.Mutex
	listeners map[string]net.Listener
	servers   map[string]*http.Server
	cancels   map[string]context.CancelFunc
}

// NewXMLRPC create a new XML RPC object
func NewXMLRPC() *XMLRPC {
	return &XMLRPC{listeners: make(map[string]net.Listener), servers: make(map[string]*http.Server), cancels: make(map[string]context.CancelFunc)}
}

// Stop network listening
func (p *XMLRPC) Stop() {
	p.mu.Lock()
	servers, cancels := p.servers, p.cancels
	p.servers = make(map[string]*http.Server)
	p.cancels = make(map[string]context.CancelFunc)
	p.listeners = make(map[string]net.Listener)
	p.mu.Unlock()
	for _, cancel := range cancels {
		cancel()
	}
	for _, server := range servers {
		_ = server.Close()
	}
}

